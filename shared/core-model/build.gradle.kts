// The shared contract module.
//
// It holds the error taxonomy that crosses the FFI boundary and the vector
// loader that proves Android, iOS, and the CLI read one set of bytes. It holds
// no encoder: `docs/format/CANONICAL_ENCODING_V1.md` section 13 says Kotlin and
// Swift consume Rust-produced records and never define an alternate canonical
// encoder for a private format.

import java.security.MessageDigest

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.android.kmp.library)
}

kotlin {
    jvmToolchain(libs.versions.jdk.get().toInt())

    jvm()
    android {
        namespace = "dev.po4yka.chur.core.model"
        compileSdk = libs.versions.androidCompileSdk.get().toInt()
        minSdk = libs.versions.androidMinSdk.get().toInt()
        // The vector suite and the error mapping are host tests: they need no
        // device, and TEST_VECTORS.md section 7 wants them running on Android.
        withHostTest {}
    }
    iosArm64()
    iosSimulatorArm64()

    sourceSets {
        commonMain.dependencies {
            implementation(libs.kotlinx.serialization.json)
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
    }
}

